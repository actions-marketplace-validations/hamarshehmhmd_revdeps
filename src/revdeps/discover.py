"""Find the most-used packages that depend on yours (via the ecosyste.ms packages API)."""
from __future__ import annotations

import json
import os
import urllib.error
import urllib.parse
import urllib.request
from typing import Callable, List, Optional

from . import __version__

API = os.environ.get("REVDEPS_API", "https://packages.ecosyste.ms/api/v1")
REGISTRY = {"npm": "npmjs.org", "pypi": "pypi.org"}
FORGES = ("https://github.com/", "https://gitlab.com/", "https://codeberg.org/", "https://bitbucket.org/")

Fetch = Callable[[str], object]


class DiscoverError(Exception):
    pass


def http_json(url: str) -> object:
    req = urllib.request.Request(url, headers={"User-Agent": f"revdeps/{__version__} (+https://github.com/hamarshehmhmd/revdeps)",
                                               "Accept": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            raise DiscoverError(f"package not found ({url})") from exc
        raise DiscoverError(f"HTTP {exc.code} from {url}") from exc
    except (urllib.error.URLError, TimeoutError, ValueError) as exc:
        raise DiscoverError(f"could not reach {url}: {exc}") from exc


def clean_repo(url: Optional[str]) -> Optional[str]:
    if not url:
        return None
    url = url.strip().rstrip("/")
    if url.startswith("git+"):
        url = url[4:]
    url = url.replace("git://", "https://").replace("http://", "https://")
    if url.endswith(".git"):
        url = url[:-4]
    if not url.startswith(FORGES):
        return None
    parts = url.split("/")
    if len(parts) < 5:
        return None
    return "/".join(parts[:5])


def dependents(name: str, ecosystem: str, top: int = 10, fetch: Fetch = http_json) -> dict:
    if ecosystem not in REGISTRY:
        raise DiscoverError(f"unsupported ecosystem {ecosystem!r}")
    base = f"{API}/registries/{REGISTRY[ecosystem]}/packages/{urllib.parse.quote(name, safe='')}"
    info = fetch(base)
    if not isinstance(info, dict):
        raise DiscoverError("unexpected API response")
    own_repo = clean_repo(info.get("repository_url"))
    per_page = min(100, max(20, top * 4))
    page = fetch(f"{base}/dependent_packages?per_page={per_page}&sort=downloads&order=desc")
    if not isinstance(page, list):
        raise DiscoverError("unexpected API response for dependents")
    picked: List[dict] = []
    seen_repos = set()
    skipped = 0
    for pkg in page:
        if not isinstance(pkg, dict):
            continue
        repo = clean_repo(pkg.get("repository_url"))
        status = pkg.get("status")
        if not repo or status in ("removed", "deprecated", "unpublished") or repo == own_repo:
            skipped += 1
            continue
        if repo in seen_repos:  # monorepos publish many packages from one repo
            continue
        seen_repos.add(repo)
        picked.append({"name": pkg.get("name"), "repo": repo, "downloads": pkg.get("downloads") or 0,
                       "dependents": pkg.get("dependent_packages_count") or 0})
        if len(picked) >= top:
            break
    picked.sort(key=lambda p: p["downloads"], reverse=True)
    return {"package": name, "ecosystem": ecosystem, "repository": own_repo,
            "dependent_packages": info.get("dependent_packages_count"), "results": picked,
            "skipped_without_repo": skipped}


def toml_str(s: str) -> str:
    return json.dumps(s)


def render_config(found: dict, lib_path: str = ".") -> str:
    eco = found["ecosystem"]
    lines = [
        "# revdeps.toml - generated by `revdeps discover --write`",
        "# Each [[dependent]] is cloned, installed, tested against the released",
        "# library (baseline), then re-tested with your local build (candidate).",
        "# Defaults are auto-detected; override install/inject/test per dependent.",
        "",
        "[library]",
        f"ecosystem = {toml_str(eco)}",
        f"name = {toml_str(found['package'])}",
        f"path = {toml_str(lib_path)}",
        "# build = \"npm run build\"   # run once before packing" if eco == "npm" else
        "# build = \"make generate\"   # run once before installing the candidate",
        "",
        "[defaults]",
        "timeout = 900",
        "",
    ]
    for d in found["results"]:
        lines += [
            "[[dependent]]",
            f"name = {toml_str(d['name'])}",
            f"repo = {toml_str(d['repo'] + '.git' if d['repo'].startswith('https://github.com/') else d['repo'])}",
            f"# {d['downloads']:,} downloads/month; {d['dependents']:,} dependent packages",
            "# subdir = \"packages/foo\"   # for monorepos",
            "# test = \"npm test\"" if eco == "npm" else "# install = \"{python} -m pip install -e .[test]\"",
            "",
        ]
    return "\n".join(lines)
