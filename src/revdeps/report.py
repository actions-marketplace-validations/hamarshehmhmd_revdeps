"""Human, Markdown and summary output."""
from __future__ import annotations

import os
import sys
from typing import List

from .runner import (ALREADY_FAILING, BROKEN, ERROR, FAIL, FIXED, FLAKY, OK, PASS, SKIPPED, Phase, Result)

STYLE = {
    OK: ("32", "✓", "ok"),
    PASS: ("32", "✓", "pass"),
    BROKEN: ("31;1", "✗", "BROKEN"),
    FAIL: ("31;1", "✗", "FAIL"),
    FLAKY: ("33", "~", "flaky"),
    FIXED: ("36", "+", "fixed"),
    ALREADY_FAILING: ("2", "·", "already failing"),
    ERROR: ("33", "!", "error"),
    SKIPPED: ("2", "-", "skipped"),
}
MD_ICON = {OK: "✅", PASS: "✅", BROKEN: "❌", FAIL: "❌", FLAKY: "⚠️", FIXED: "🟦", ALREADY_FAILING: "⬜",
           ERROR: "⚠️", SKIPPED: "➖"}


def use_color(mode: str, stream=sys.stdout) -> bool:
    if mode == "always":
        return True
    if mode == "never" or os.environ.get("NO_COLOR"):
        return False
    return hasattr(stream, "isatty") and stream.isatty()


def paint(text: str, code: str, color: bool) -> str:
    return f"\x1b[{code}m{text}\x1b[0m" if color else text


def phase_str(p: Phase) -> str:
    if p is None:
        return "-"
    if p.timed_out:
        return f"timeout {p.seconds:.0f}s"
    secs = f"{p.seconds:.1f}s" if p.seconds < 10 else f"{p.seconds:.0f}s"
    return f"{'pass' if p.passed else 'fail'} {secs}"


def line(r: Result, color: bool) -> str:
    code, icon, label = STYLE.get(r.status, ("0", "?", r.status))
    head = paint(f"{icon} {label:<15}", code, color)
    extra = []
    if r.baseline or r.candidate:
        extra.append(f"baseline {phase_str(r.baseline)} → candidate {phase_str(r.candidate)}")
    if r.stage and r.status in (ERROR, BROKEN) and r.stage != "":
        extra.append(f"[{r.stage}]")
    if r.detail:
        extra.append(r.detail)
    commit = f"@{r.commit}" if r.commit else ""
    return f"{head} {r.name}{paint(commit, '2', color)}  {paint('  '.join(extra), '2', color)}".rstrip()


def details(r: Result, color: bool, max_tests: int = 8) -> List[str]:
    out = []
    if r.new_failures:
        out.append(paint(f"    newly failing ({len(r.new_failures)}):", "31", color))
        for t in r.new_failures[:max_tests]:
            msg = r.messages.get(t)
            out.append(f"      - {t}" + (paint(f"  ({msg})", "2", color) if msg else ""))
        if len(r.new_failures) > max_tests:
            out.append(f"      … {len(r.new_failures) - max_tests} more")
    if r.new_passes and r.status in (FIXED, OK, BROKEN):
        out.append(paint(f"    newly passing ({len(r.new_passes)}): " + ", ".join(r.new_passes[:4]), "36", color))
    if r.status in (BROKEN, FAIL, ERROR) and r.tail and not r.messages:
        out.append(paint("    last log lines:", "2", color))
        out += [paint("      │ " + t[:150], "2", color) for t in r.tail[:10]]
    if r.status in (BROKEN, FAIL, ERROR, FLAKY) and r.log:
        out.append(paint(f"    log: {r.log}", "2", color))
    return out


def counts(results: List[Result]) -> dict:
    c: dict = {}
    for r in results:
        c[r.status] = c.get(r.status, 0) + 1
    return c


def summary(results: List[Result], color: bool) -> str:
    c = counts(results)
    order = [BROKEN, FAIL, ERROR, FLAKY, OK, PASS, FIXED, ALREADY_FAILING, SKIPPED]
    parts = [paint(f"{c[s]} {STYLE[s][2].lower()}", STYLE[s][0], color) for s in order if c.get(s)]
    return f"{len(results)} dependents: " + ", ".join(parts)


def markdown(results: List[Result], library: str, title: str = "revdeps report") -> str:
    out = [f"## {title}: `{library}`", "", summary(results, False), "",
           "| | dependent | baseline | candidate | notes |", "|---|---|---|---|---|"]
    for r in results:
        notes = []
        if r.detail:
            notes.append(r.detail)
        if r.new_failures:
            shown = ", ".join(f"`{t}`" for t in r.new_failures[:5])
            more = f" +{len(r.new_failures) - 5} more" if len(r.new_failures) > 5 else ""
            notes.append(f"newly failing: {shown}{more}")
        if r.new_passes and r.status != BROKEN:
            notes.append("newly passing: " + ", ".join(f"`{t}`" for t in r.new_passes[:5]))
        if r.stage and r.status == ERROR:
            notes.append(f"stage: {r.stage}")
        name = f"[{r.name}]({r.source})" if r.source.startswith("http") else r.name
        if r.commit:
            name += f" @`{r.commit}`"
        out.append(f"| {MD_ICON.get(r.status, '')} {STYLE.get(r.status, ('', '', r.status))[2]} | {name} | "
                   f"{phase_str(r.baseline)} | {phase_str(r.candidate)} | {'; '.join(notes)} |")
    out += ["", "_Generated by [revdeps](https://github.com/hamarshehmhmd/revdeps)._", ""]
    return "\n".join(out)
